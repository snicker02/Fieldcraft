// blockcore/mcpack.js
// Wraps one or more .mcstructure files into a Bedrock behavior pack (.mcpack).
// Structures live at structures/<namespace>/<name>.mcstructure and are placed
// in game with:  /structure load <namespace>:<name> <x> <y> <z>

import { ZipWriter } from './zip.js';

export function uuid4() {
  const b = new Uint8Array(16);
  const c = globalThis.crypto;
  if (c && c.getRandomValues) c.getRandomValues(b);
  else for (let i = 0; i < 16; i++) b[i] = (Math.random() * 256) | 0;
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = [...b].map(v => v.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

/** Bedrock identifiers: lowercase, alphanumerics, underscore, hyphen. */
export function sanitizeId(s, fallback = 'field') {
  const out = String(s).toLowerCase().replace(/[^a-z0-9_-]+/g, '_').replace(/^_+|_+$/g, '');
  return out.length ? out : fallback;
}

/**
 * @param {object} opts
 *   name, description   pack metadata
 *   namespace           structure namespace (default 'fieldcraft')
 *   structures          [{ name, bytes }]
 *   extraFiles          [{ path, data }] e.g. the placement guide
 *   minEngineVersion    [major, minor, patch] (default [1,21,0])
 *   packVersion         [major, minor, patch] (default [1,0,0])
 * @returns {{bytes:Uint8Array, manifest:object, paths:string[]}}
 */
export function buildMcPack(opts) {
  const namespace = sanitizeId(opts.namespace || 'fieldcraft', 'fieldcraft');
  const packVersion = opts.packVersion || [1, 0, 0];
  const manifest = {
    format_version: 2,
    header: {
      name: opts.name || 'Fieldcraft structures',
      description: opts.description || 'Structures generated by Fieldcraft',
      uuid: uuid4(),
      version: packVersion,
      min_engine_version: opts.minEngineVersion || [1, 21, 0],
    },
    modules: [
      {
        type: 'data',
        uuid: uuid4(),
        version: packVersion,
        description: opts.description || 'Structures generated by Fieldcraft',
      },
    ],
  };

  const zip = new ZipWriter();
  zip.add('manifest.json', JSON.stringify(manifest, null, 2));

  const paths = [];
  for (const s of opts.structures || []) {
    const id = sanitizeId(s.name);
    const path = `structures/${namespace}/${id}.mcstructure`;
    zip.add(path, s.bytes);
    paths.push(path);
  }
  for (const f of opts.extraFiles || []) zip.add(f.path, f.data);

  return { bytes: zip.build(), manifest, paths, namespace };
}
